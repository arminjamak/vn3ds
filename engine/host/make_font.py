"""Bake a glyph atlas for the desktop test build (host/font_data.h).

The 3DS build uses the console's system font; this only exists so the
software renderer can show text. Run once:

    python3 engine/host/make_font.py [font.ttf]
"""

import os
import sys

from PIL import Image, ImageDraw, ImageFont

SIZE = 24          # px; with LINE_FEED 30 this approximates the 3DS system font
LINE_FEED = 30
ASCENT_PAD = 3
CANDIDATES = [
    "/System/Library/Fonts/Supplemental/Arial Unicode.ttf",
    "/System/Library/Fonts/Supplemental/Arial.ttf",
    "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
]

CODEPOINTS = (list(range(32, 127)) + list(range(160, 256)) +
              [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2026, 0x2022, 0x266A])


def main():
    # Default: Pillow's bundled Aileron (CC0, public domain), so the baked
    # atlas can be redistributed. Pass a .ttf to use another font.
    if len(sys.argv) > 1:
        path = sys.argv[1]
        font = ImageFont.truetype(path, SIZE)
    else:
        font = ImageFont.load_default(size=SIZE)
        path = "Aileron (Pillow's bundled CC0 font)"
    ascent, _ = font.getmetrics()
    glyphs = []
    atlas_w = 512
    x = y = 0
    row_h = 0
    tiles = []
    for cp in CODEPOINTS:
        ch = chr(cp)
        bbox = font.getbbox(ch)
        adv = font.getlength(ch)
        w = max(1, bbox[2] - bbox[0])
        h = max(1, bbox[3] - bbox[1])
        if x + w + 1 > atlas_w:
            x = 0
            y += row_h + 1
            row_h = 0
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-bbox[0], -bbox[1]), ch, font=font, fill=255)
        tiles.append((img, x, y))
        glyphs.append((cp, x, y, w, h, bbox[0], bbox[1] + ASCENT_PAD, adv))
        x += w + 1
        row_h = max(row_h, h)
    atlas_h = y + row_h + 1
    atlas = Image.new("L", (atlas_w, atlas_h), 0)
    for img, gx, gy in tiles:
        atlas.paste(img, (gx, gy))
    data = atlas.tobytes()
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "font_data.h")
    with open(out, "w") as f:
        f.write("/* generated by make_font.py from %s */\n" % (os.path.basename(path) if os.path.exists(path) else path))
        f.write("#define FONT_ATLAS_W %d\n#define FONT_ATLAS_H %d\n" % (atlas_w, atlas_h))
        f.write("#define FONT_LINE_FEED %d\n#define FONT_NGLYPHS %d\n" % (LINE_FEED, len(glyphs)))
        f.write("typedef struct { unsigned cp; short x, y, w, h, ox, oy; float adv; } FontGlyph;\n")
        f.write("static const FontGlyph FONT_GLYPHS[] = {\n")
        for g in glyphs:
            f.write("  {%d,%d,%d,%d,%d,%d,%d,%.3ff},\n" % g)
        f.write("};\nstatic const unsigned char FONT_ATLAS[] = {\n")
        for i in range(0, len(data), 32):
            f.write("  " + ",".join(str(b) for b in data[i:i + 32]) + ",\n")
        f.write("};\n")
    print("wrote", out, f"({atlas_w}x{atlas_h}, ascent {ascent})")


if __name__ == "__main__":
    main()
